import {chromium,launchOptions,artifactPath} from './browser-runtime.mjs';
import assert from 'node:assert/strict';
const browser=await chromium.launch(launchOptions);
try {
 const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:41732');await page.click('#welcomeNewButton');
 const source='正文引用[^sample]。\n\n[^sample]: **粗体**、*斜体*、`code`、==高亮== 和 [链接](https://example.com)。\n    第二行';
 await page.evaluate(async source=>{const {EditorView}=await import('/node_modules/@codemirror/view/dist/index.js');window.v=EditorView.findFromDOM(document.querySelector('#editor .cm-content'));v.dispatch({changes:{from:0,to:v.state.doc.length,insert:source},selection:{anchor:0}});},source);
 await page.click('#notesButton');
 const note=page.locator('.note-body');
 await page.waitForFunction(()=>document.querySelector('.note-body .tok-strong')?.textContent==='粗体');
 assert.equal(await note.locator('.tok-emphasis').textContent(),'斜体');
 assert.equal(await note.locator('.cm-leaf-inline-code').textContent(),'code');
 assert.equal(await note.locator('.leaf-highlight').textContent(),'高亮');
 assert.equal(await note.locator('[data-leaf-link]').textContent(),'链接');
 assert.ok(!(await note.innerText()).includes('**'));
 const layout=await note.locator('.cm-content').evaluate(el=>({padding:getComputedStyle(el).padding,height:el.getBoundingClientRect().height}));
 assert.equal(layout.padding,'0px','sidebar must not inherit document page padding');
 assert.ok(layout.height<180,'short notes must retain a compact sidebar layout');
 const mode=async name=>{await page.click('#readingToggle');await page.locator(`[data-mode=${name}]`).click();};
 const text=()=>page.evaluate(()=>v.state.doc.toString());
 await page.evaluate(()=>{window.card=document.querySelector('.note-card');const n=card._noteEditor.view;n.dispatch({selection:{anchor:2}});n.focus();});
 await page.waitForFunction(()=>document.querySelector('.note-body').textContent.includes('**粗体**'));
 await page.keyboard.insertText('新');
 assert.ok((await text()).includes('**新粗体**'));
 await page.keyboard.press('ControlOrMeta+z');assert.equal(await text(),source,'note undo uses the document history');
 assert.ok(!(await note.evaluate(el=>el.value)).includes('新粗体'),'undo must restore the sidebar buffer too');
 await page.click('#redoButton');assert.ok((await text()).includes('**新粗体**'));
 await page.click('#undoButton');assert.equal(await text(),source);
 await mode('source');
 assert.ok((await note.innerText()).includes('**粗体**'));
 assert.ok((await note.innerText()).includes('[链接](https://example.com)'));
 assert.equal(await note.locator('[contenteditable=true]').count(),1);
 await mode('reading');
 assert.equal(await note.locator('strong').textContent(),'粗体');
 assert.equal(await note.locator('em').textContent(),'斜体');
 assert.equal(await note.locator('code').textContent(),'code');
 assert.equal(await note.locator('mark').textContent(),'高亮');
 assert.equal(await note.locator('[data-leaf-link]').textContent(),'链接');
 assert.equal(await note.locator('[contenteditable=true],textarea').count(),0);
 assert.equal(await page.locator('.note-delete').count(),0);
 assert.equal(await text(),source,'mode switches cannot change source');
 await page.screenshot({path:artifactPath('leaf-notes-rendered-reading.png')});
 await page.click('[data-close=notes]');await page.click('#notesButton');
 assert.equal(await note.locator('strong').textContent(),'粗体','reopening retains reading mode');
 await mode('edit');
 await page.waitForFunction(()=>document.querySelector('.note-body .tok-strong')?.textContent==='粗体');
 assert.equal(await note.locator('[contenteditable=true]').count(),1);
 assert.equal(await page.locator('.note-delete').count(),1);
 assert.equal(await text(),source);
 const high=page.locator('[data-format=highlight]');assert.equal(await high.locator('svg').count(),1);
 await page.evaluate(()=>{v.dispatch({selection:{anchor:0,head:2}});v.focus();});
 await high.click();assert.ok((await text()).startsWith('==正文=='));
 await page.click('#undoButton');assert.equal(await text(),source);
 await page.setViewportSize({width:700,height:800});
 assert.equal(await high.isVisible(),true);
 await page.screenshot({path:artifactPath('leaf-highlight-toolbar-narrow.png')});
 assert.deepEqual(errors,[]);
 console.log('PASS footnote edit/reading/source rendering, shared history, reopen, and highlighter icon');
}finally{await browser.close()}
