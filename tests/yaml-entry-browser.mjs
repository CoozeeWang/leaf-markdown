import { chromium, launchOptions, artifactPath } from './browser-runtime.mjs';
import assert from 'node:assert/strict';
const browser=await chromium.launch(launchOptions);
try {
 const page=await browser.newPage(), errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:41732');await page.click('#welcomeNewButton');
 await page.evaluate(async()=>{const {EditorView}=await import('/node_modules/@codemirror/view/dist/index.js');window.v=EditorView.findFromDOM(document.querySelector('.cm-content'));});
 const setup=async(doc,head=0)=>page.evaluate(({doc,head})=>{v.dispatch({changes:{from:0,to:v.state.doc.length,insert:doc},selection:{anchor:head}});v.focus()},{doc,head});
 const source=()=>page.evaluate(()=>v.state.doc.toString());
 await setup('\n# 标题\n\n正文');
 await page.keyboard.type('---');
 await page.getByRole('textbox',{name:'新属性名',exact:true}).waitFor();
 assert.equal(await source(),'---\n\n---\n\n# 标题\n\n正文');
 await page.getByRole('textbox',{name:'新属性名',exact:true}).fill('version');
 await page.getByRole('textbox',{name:'新属性值',exact:true}).fill('v1');
 assert.ok(!(await source()).includes('"version"'),'moving between name and value must not submit early');
 assert.equal(await page.getByRole('button',{name:'确认添加属性',exact:true}).count(),0);
 await page.locator('.brand').click();
 const value=page.getByRole('textbox',{name:'version',exact:true});
 await value.fill('v2');assert.ok((await source()).includes('"version": "v2"'));
 await page.getByRole('button',{name:'编辑此块 Markdown 源码'}).click();
 const before=await source();await page.getByRole('textbox',{name:'文档属性源码',exact:true}).press('Enter');
 assert.equal((await source()).length,before.length+1);
 await page.getByRole('button',{name:'返回实时渲染',exact:true}).click();
 await setup('# 正文\n\n');await page.evaluate(()=>{v.dispatch({selection:{anchor:v.state.doc.length}});v.focus()});
 await page.keyboard.type('---');assert.equal(await source(),'# 正文\n\n---');
 await setup('# 正文');await page.click('#commandsButton');await page.fill('#paletteInput','文档属性');await page.getByRole('option',{name:'文档属性',exact:true}).click();
 await page.getByRole('textbox',{name:'新属性名',exact:true}).waitFor();
 assert.equal(await source(),'---\n\n---\n\n# 正文');
 await page.keyboard.press('ControlOrMeta+z');assert.equal(await source(),'# 正文');
 await page.click('#commandsButton');await page.fill('#paletteInput','文档属性');await page.getByRole('option',{name:'文档属性',exact:true}).click();
 await page.getByRole('textbox',{name:'新属性名',exact:true}).fill('状态');
 await page.getByRole('textbox',{name:'新属性值',exact:true}).fill('草稿');
 await page.locator('.brand').click();
 await page.getByRole('textbox',{name:'状态',exact:true}).fill('完成');
 assert.ok((await source()).includes('"状态": "完成"'));
 await page.screenshot({path:artifactPath('leaf-yaml-entry.png')});
 assert.deepEqual(errors,[]);
 console.log('PASS YAML typing entry, separate fields, live values, raw Enter, body rule and properties button');
} finally {await browser.close()}
