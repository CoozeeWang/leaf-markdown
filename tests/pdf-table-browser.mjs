import { chromium, launchOptions, artifactPath } from './browser-runtime.mjs';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
const browser = await chromium.launch(launchOptions);
try {
  const page = await browser.newPage({viewport:{width:1100,height:900}});
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:41732'); await page.click('#welcomeNewButton');
  await page.locator('.cm-content').fill('# 按钮导出\n\n未保存内容也应出现在快照中。');
  const popupEvent = page.waitForEvent('popup');
  await page.click('#exportMenuButton');await page.click('#exportButton');
  const popup = await popupEvent;
  await popup.locator('article h1').waitFor();
  assert.equal(await popup.locator('article h1').innerText(),'按钮导出');
  assert.ok((await popup.locator('article').innerText()).includes('未保存内容'));
  await popup.close();
  const table = '| ID | 详细说明 | 状态 |\n| --- | --- | --- |\n| A1 | 这是一段较长的说明，应该获得更多列宽，并且在窄窗口中自然换行，不遮挡其他单元格的内容。 | 完成 |';
  await page.evaluate(async table => {
    const {createLeafEditor} = await import('/src/editor.js');
    document.querySelector('#editor').replaceChildren();
    window.fixture = createLeafEditor({parent:document.querySelector('#editor'),doc:table});
  }, table);
  const widths = await page.locator('.leaf-table th').evaluateAll(cells => cells.map(c => c.getBoundingClientRect().width));
  assert.ok(widths[1] > widths[0] * 1.5);
  await page.locator('.leaf-table td .leaf-cell-preview').nth(1).click();
  const input = page.locator('textarea[data-row="1"][data-col="1"]');
  await input.fill('新内容，' .repeat(55));
  await page.setViewportSize({width:760,height:900});
  await page.waitForTimeout(100);
  assert.ok(await input.evaluate(el => el.clientHeight >= el.scrollHeight - 2));
  assert.ok((await page.evaluate(() => fixture.getValue())).includes('新内容'));
  await page.screenshot({path:artifactPath('leaf-table-adaptive.png')});
  const rows = Array.from({length:30},(_,i)=>`| R${i+1} | 第 ${i+1} 项：${'说明文字帮助检验跨页排版和行高。'.repeat(i % 3 + 1)} | 待办 |`).join('\n');
  const source = `---\nversion: v1\nupdated: 2026-09-08\n---\n\n# 1.导出测试\n\n正文包含 **粗体**、*斜体*、\`inline code\` 和 ==高亮内容==。\n\n## 1.1 阅读路线\n\n- 列表第一项\n- 列表第二项\n  - 嵌套项目\n\n3. 第三项\n4. 第四项\n\n> 引用说明，保留正文风格。\n\n\`\`\`js\nconst value = '<script>安全文本</script>';\nconsole.log(value);\n\`\`\`\n\n${table}\n${rows}\n\n## 1.2 文档末尾\n\nFINAL-CONTENT-END\n\n<img src=x onerror=alert(1)>`;
  await page.evaluate(source => sessionStorage.setItem('fixture-pdf',JSON.stringify({source,name:'导出测试.md',numbered:true})),source + '\n\n> [!warning]- 注意事项\n> PDF 中应展开这段内容。<br>第二行提示。\n>\n> - 检查列表\n');
  await page.goto('http://127.0.0.1:41732/?export=fixture-pdf');
  await page.locator('article h1').waitFor();
  assert.equal(await page.locator('article h1').innerText(),'1. 导出测试');
  assert.equal(await page.locator('.print-properties').count(),0);
  await page.check('#properties');
  assert.ok((await page.locator('.print-properties').innerText()).includes('v1'));
  assert.equal(await page.locator('article img, article script').count(),0);
  assert.equal(await page.locator('article mark').innerText(),'高亮内容');
  assert.equal(await page.locator('article ol').getAttribute('start'),'3');
  assert.ok((await page.locator('article').innerText()).includes('FINAL-CONTENT-END'));
  await page.uncheck('#numbered');
  assert.equal(await page.locator('article h1').innerText(),'1.导出测试');
  await page.check('#numbered');
  await mkdir('tmp/pdfs',{recursive:true});
  assert.equal(await page.locator('article .leaf-callout').count(),1);
  assert.equal(await page.locator('article .leaf-callout br').count(),1);
  const css = await readFile('src/pdf-export.css', 'utf8') + await readFile('src/callout.css', 'utf8');
  const article = await page.locator('article').evaluate(el => el.outerHTML);
  await writeFile('tmp/pdfs/native-fixture.html', `<!doctype html><html class="native-print"><meta charset="utf-8"><style>${css}\n@page { margin: 0; }</style><body>${article}</body></html>`);
  await page.pdf({path:'tmp/pdfs/leaf-export-regression.pdf',printBackground:true,preferCSSPageSize:true});
  assert.deepEqual(errors,[]);
  console.log('PDF renderer, properties, numbering, safe HTML and adaptive cell editing passed');
} finally { await browser.close(); }
